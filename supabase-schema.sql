create or replace function public.capture_project_audit()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  old_row jsonb;
  new_row jsonb;
  audit_record_id text;
  bucket_name text;
begin
  if tg_op = 'INSERT' then
    new_row := to_jsonb(new);
  elsif tg_op = 'UPDATE' then
    old_row := to_jsonb(old);
    new_row := to_jsonb(new);
  else
    old_row := to_jsonb(old);
  end if;

  if tg_table_schema = 'storage' then
    bucket_name := coalesce(new_row ->> 'bucket_id', old_row ->> 'bucket_id');
    if coalesce(bucket_name, '') <> 'project-attachments' then
      if tg_op = 'DELETE' then return old; end if;
      return new;
    end if;
    audit_record_id := coalesce(new_row ->> 'name', old_row ->> 'name', new_row ->> 'id', old_row ->> 'id');
  elsif tg_table_name = 'projects' then
    audit_record_id := coalesce(new_row ->> 'id', old_row ->> 'id');
  else
    audit_record_id := coalesce(new_row ->> 'project_id', old_row ->> 'project_id');
  end if;

  insert into public.project_audit_log (
    table_name, record_id, operation, actor_id, actor_email, old_data, new_data
  ) values (
    tg_table_schema || '.' || tg_table_name,
    coalesce(audit_record_id, 'unknown'),
    tg_op,
    auth.uid(),
    nullif(lower(coalesce(auth.jwt() ->> 'email', '')), ''),
    old_row,
    new_row
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.capture_project_audit() from public, anon, authenticated;

