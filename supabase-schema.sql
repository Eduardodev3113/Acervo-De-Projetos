create or replace function public.claim_project(target_project_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  project_status text;
begin
  if auth.uid() is null then
    raise exception 'Entre com sua conta institucional para assumir este projeto.';
  end if;

  if not (
    lower(coalesce(auth.jwt() ->> 'email', '')) like '%@ifsc.edu.br'
    or lower(coalesce(auth.jwt() ->> 'email', '')) like '%@aluno.ifsc.edu.br'
  ) then
    raise exception 'Use uma conta com e-mail institucional do IFSC para assumir projetos.';
  end if;

  select status into project_status
  from public.projects
  where id = target_project_id
  for update;

  if not found then
    raise exception 'Projeto não encontrado no acervo.';
  end if;

  if project_status = 'Em andamento' then
    raise exception 'Este projeto já está em andamento e não pode ser assumido novamente.';
  end if;

  if exists (
    select 1 from public.projects
    where version_of = target_project_id
      and status in ('Em andamento', 'Planejamento')
  ) then
    raise exception 'Este projeto já possui uma continuação em andamento.';
  end if;

  delete from public.project_claims
  where project_id = target_project_id and expires_at <= now();

  insert into public.project_claims (project_id, claimant_id, expires_at)
  values (target_project_id, auth.uid(), now() + interval '15 minutes');
exception
  when unique_violation then
    raise exception 'Este projeto já está sendo assumido por alguém. Tente novamente mais tarde.';
end;
$$;

create or replace function public.renew_project_claim(target_project_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  update public.project_claims
  set expires_at = now() + interval '15 minutes'
  where project_id = target_project_id
    and claimant_id = auth.uid()
    and expires_at > now();

  if not found then
    raise exception 'A reserva deste projeto expirou. Volte ao acervo e tente assumir novamente.';
  end if;
end;
$$;

create or replace function public.release_project_claim(target_project_id uuid)
returns void
language sql
security definer
set search_path = public, auth
as $$
  delete from public.project_claims
  where project_id = target_project_id and claimant_id = auth.uid();
$$;

create or replace function public.append_project_images(target_project_id uuid, new_images jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  project_status text;
  current_attachments jsonb;
  project_email text;
  path_prefix text;
begin
  if auth.uid() is null then
    raise exception 'Entre com sua conta institucional para adicionar imagens.';
  end if;

  select status, attachments into project_status, current_attachments
  from public.projects
  where id = target_project_id
  for update;

  if not found then
    raise exception 'Projeto não encontrado no acervo.';
  end if;
  if lower(btrim(project_status)) <> 'concluído' then
    raise exception 'Imagens só podem ser adicionadas a projetos concluídos.';
  end if;

  project_email := lower(coalesce(auth.jwt() ->> 'email', ''));
  if project_email <> 'eduardo.r2008@aluno.ifsc.edu.br' and not exists (
    select 1 from public.projects
    where version_of = target_project_id
      and owner_id = auth.uid()
      and status in ('Em andamento', 'Planejamento')
  ) then
    raise exception 'Somente o administrador ou quem está continuando este projeto pode adicionar imagens.';
  end if;

  if jsonb_typeof(new_images) is distinct from 'array' then
    raise exception 'Envie uma lista de imagens válida.';
  end if;
  if jsonb_array_length(new_images) < 1 or jsonb_array_length(new_images) > 10 then
    raise exception 'Envie de 1 a 10 imagens por vez.';
  end if;

  current_attachments := coalesce(current_attachments, '[]'::jsonb);
  if jsonb_array_length(current_attachments) + jsonb_array_length(new_images) > 30 then
    raise exception 'O projeto atingiu o limite de 30 anexos.';
  end if;

  path_prefix := auth.uid()::text || '/' || target_project_id::text || '/';
  if exists (
    select 1
    from jsonb_array_elements(new_images) as item(image)
    where jsonb_typeof(item.image) <> 'object'
      or coalesce(item.image ->> 'name', '') !~* '\.(png|jpe?g)$'
      or coalesce(item.image ->> 'path', '') not like path_prefix || '%'
      or not exists (
        select 1 from storage.objects
        where bucket_id = 'project-attachments'
          and name = item.image ->> 'path'
      )
  ) then
    raise exception 'Uma ou mais imagens não são válidas ou não foram enviadas.';
  end if;

  update public.projects
  set attachments = current_attachments || new_images
  where id = target_project_id
  returning attachments into current_attachments;

  return current_attachments;
end;
$$;

